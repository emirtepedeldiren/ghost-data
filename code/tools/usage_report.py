"""Write code/evaluation/usage_report.md from the cached-call index (code/llm_cache/calls.jsonl) and list prices.

Usage: python3 code/tools/usage_report.py
The frozen run is served from cache (D26), so its usage is the usage of the original API calls that produced the
cached responses. Each row of calls.jsonl is one original call, matched to its cache entry (cache_key), with the
call-log timestamp and the token counts the provider returned.
"""
from __future__ import annotations

import collections
import json
import sys
import tomllib
from pathlib import Path

CODE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(CODE))
from contract import DATASET_DIR  # noqa: E402

N_REQUESTS = sum(1 for _ in (DATASET_DIR / "deletion_requests.csv").open(encoding="utf-8")) - 1


def main() -> int:
    calls = [json.loads(l) for l in (CODE / "llm_cache" / "calls.jsonl").open(encoding="utf-8")]
    prices = tomllib.loads((CODE / "config.toml").read_text(encoding="utf-8"))["llm"]["prices"]
    frozen = tomllib.loads((CODE / "config" / "frozen_v1.toml").read_text(encoding="utf-8"))

    def cost(model, tin, tout):
        p = prices[model]
        return tin * p["input"] / 1e6 + tout * p["output"] / 1e6

    def table(rows, per_request: bool):
        agg = collections.OrderedDict()
        for c in rows:
            a = agg.setdefault((c["provider"], c["model"], c["task"]), [0, 0, 0])
            a[0] += 1
            a[1] += c["input_tokens"]
            a[2] += c["output_tokens"]
        head = "| Provider | Model | Task | Calls | Input tokens | Output tokens | Total tokens | Avg tokens / call |"
        sep = "|---|---|---|---|---|---|---|---|"
        if per_request:
            head += f" Avg tokens / request (n={N_REQUESTS}) | Est. cost (USD) | Est. cost / request |"
            sep += "---|---|---|"
        else:
            head += " Est. cost (USD) |"
            sep += "---|"
        out = [head, sep]
        tot = [0, 0, 0, 0.0]
        for (prov, model, task), (n, tin, tout) in agg.items():
            c = cost(model, tin, tout)
            tot = [tot[0] + n, tot[1] + tin, tot[2] + tout, tot[3] + c]
            row = f"| {prov} | {model} | {task} | {n} | {tin:,} | {tout:,} | {tin + tout:,} | {(tin + tout) / n:,.0f} |"
            row += f" {(tin + tout) / N_REQUESTS:,.1f} | ${c:.4f} | ${c / N_REQUESTS:.6f} |" if per_request else f" ${c:.4f} |"
            out.append(row)
        n, tin, tout, c = tot
        row = f"| **overall** | | | **{n}** | **{tin:,}** | **{tout:,}** | **{tin + tout:,}** | **{(tin + tout) / n:,.0f}** |"
        row += f" **{(tin + tout) / N_REQUESTS:,.1f}** | **${c:.4f}** | **${c / N_REQUESTS:.6f}** |" if per_request else f" **${c:.4f}** |"
        out.append(row)
        return out

    prod = [c for c in calls if c["purpose"] == "production"]
    evals = [c for c in calls if c["purpose"] != "production"]
    ts = sorted(c["created_ts"] for c in prod)
    md = [
        "# Usage report: final full-dataset run",
        "",
        "Generated by `python3 code/tools/usage_report.py` from `code/llm_cache/calls.jsonl` (one row per original API call, "
        "matched to its cached response) and the list prices in `code/config.toml`.",
        "",
        "## How the final run used the models",
        "",
        f"- The submitted `output.csv` (518 rows) comes from the frozen run `python3 code/main.py` with `code/config/frozen_v1.toml` "
        f"(models: intent `{frozen['llm']['models']['intent']}`, screenshots `{frozen['llm']['models']['vision']}`, provider "
        f"`{frozen['llm']['provider']}`).",
        "- **The final run was served entirely from the response cache: 0 live API calls** (D26, free tier). The run is cache-only: "
        "a cache miss aborts it, and no API key is needed.",
        f"- The cached responses were produced by **{len(prod)} original API calls on 2026-10-24 between {ts[0]} and {ts[-1]}** "
        "(call-log timestamps, UTC). The usage below is the usage of those calls, which is what the final output costs.",
        "- The LLM is used in exactly two places: request intent (5 batched calls classify the 398 unique request texts of the eval "
        "and sample files, 80 per call) and screenshot transcription (1 call per PNG, 11 PNGs). Everything else is deterministic code.",
        "- Average tokens and cost per request divide the totals by the 518 eval requests. The intent batches also cover the 32 sample "
        "texts; they are not split out.",
        "",
        "## Per-model and overall totals (production: calls behind output.csv)",
        "",
        *table(prod, per_request=True),
        "",
        "List prices (USD per 1M tokens, https://ai.google.dev/gemini-api/docs/pricing, page updated 2026-10-22): " + "; ".join(
            f"`{m}` input ${prices[m]['input']:.2f} / output ${prices[m]['output']:.2f}" for m in sorted({c['model'] for c in prod})) +
        ". Output tokens include thinking tokens. The calls ran on the free tier, so the actual charge was $0; the costs above are list-price estimates.",
        "",
        "## Evaluation-only calls (not part of the final output)",
        "",
        "The participant evaluation cases E1-E3 (`code/evaluation/custom_cases.py`) needed their new request texts classified, "
        "in a separate intent batch so the production batches stayed valid. This call is not part of the production totals above.",
        "",
        *table(evals, per_request=False),
        "",
        "## Each original call",
        "",
        "| # | Purpose | Model | Task | Input | Created (UTC) | Input tokens | Output tokens |",
        "|---|---|---|---|---|---|---|---|",
        *[f"| {i} | {c['purpose']} | {c['model']} | {c['task']} | {c['image'] or 'batch of request texts'} | {c['created_ts']} | "
          f"{c['input_tokens']:,} | {c['output_tokens']:,} |" for i, c in enumerate(calls, 1)],
        "",
        "## Development calls (context, not the final run)",
        "",
        "Before the freeze, development also used 16 calls on `gemini-3.6-flash` (unbatched intent, abandoned at the free-tier quota) and "
        "11 calls on `gemini-2.5-flash` (the screenshot model comparison, D17). They are listed in `evaluation_report.md` §6 and did not "
        "contribute to `output.csv`.",
        "",
    ]
    out = CODE / "evaluation" / "usage_report.md"
    out.write_text("\n".join(md), encoding="utf-8")
    print(f"written {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
